#!/usr/bin/env python3
"""Generate Mermaid UML dependency diagrams from cargo-modules, not hand-written models.

Requires cargo-modules and Graphviz. --render additionally requires Mermaid CLI
(mmdc); Graphviz also renders the complete symbol graph for large-diagram browsing.
"""
import argparse
import html
import json
from pathlib import Path
import shlex
import subprocess


ROOT = Path(__file__).resolve().parents[1]
VIEWS = {
    "modules": ["--lib", "--no-externs", "--no-sysroot", "--no-fns", "--no-types"],
    "types": ["--lib", "--no-externs", "--no-sysroot", "--no-fns", "--no-modules"],
    "symbols": ["--lib", "--no-externs", "--no-sysroot"],
    "cli": ["--bin", "nacre", "--no-sysroot"],
}


def mermaid(graph: dict, command: list[str], name: str) -> str:
    lines = [
        "---", f"title: Nacre - autogenerated {name}", "---", "classDiagram", "    direction LR",
        "    %% GENERATED by scripts/generate_uml.py; do not edit manually.",
        "    %% Source: " + shlex.join(command),
        "    %% declares = lexical item containment, NOT runtime object composition.",
        "    %% uses = static dependency reported by cargo-modules, NOT execution order.",
    ]
    for item in graph.get("objects", []):
        label = html.escape(item["name"], quote=True)
        declaration = item.get("label", "").split("|", 1)[0]
        kind = declaration.rsplit(" ", 1)[-1]
        identifier = f'n{item["_gvid"]}'
        lines.extend([f'    class {identifier}["{label}"] {{', f"        <<{kind}>>", "    }"])
    for edge in graph.get("edges", []):
        relation = edge.get("label", "uses")
        if relation == "owns":
            arrow, label = "-->", "declares"
        else:
            arrow, label = "..>", html.escape(relation, quote=True)
        lines.append(f'    n{edge["tail"]} {arrow} n{edge["head"]} : {label}')
    return "\n".join(lines) + "\n"


def module_diagrams(graph: dict):
    """Assign each relationship to its source's nearest lexical Rust module."""
    objects = {item["_gvid"]: item for item in graph["objects"]}
    parents = {edge["head"]: edge["tail"] for edge in graph["edges"] if edge.get("label") == "owns"}
    owners = {}
    for identifier in objects:
        owner = identifier
        while objects[owner]["label"].split("|", 1)[0].rsplit(" ", 1)[-1] not in {"mod", "crate"}:
            owner = parents[owner]
        owners[identifier] = owner
    for owner in sorted(set(owners.values()), key=lambda key: objects[key]["name"]):
        edges = [edge for edge in graph["edges"] if owners[edge["tail"]] == owner]
        identifiers = {key for key, value in owners.items() if value == owner}
        identifiers.update(edge[side] for edge in edges for side in ("tail", "head"))
        yield objects[owner]["name"], {
            "objects": [item for key, item in objects.items() if key in identifiers],
            "edges": edges,
        }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "docs/uml/generated")
    parser.add_argument("--render", action="store_true", help="also render Mermaid SVG files with mmdc")
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    results, diagrams = [], []
    for name, options in VIEWS.items():
        command = ["cargo", "modules", "dependencies", *options]
        dot = subprocess.run(command, cwd=ROOT, text=True, stdout=subprocess.PIPE, check=True).stdout
        # Graphviz parses the DOT grammar; no regular-expression extraction or invented edges.
        converted = subprocess.run(
            ["dot", "-Tdot_json"], input=dot, text=True, stdout=subprocess.PIPE, check=True,
        ).stdout
        graph = json.loads(converted)
        (output / f"{name}.dot").write_text(dot)
        nodes, edges = len(graph.get("objects", [])), len(graph.get("edges", []))
        results.append((name, nodes, edges, shlex.join(command)))
        print(f"{name}: {nodes} symbols, {edges} relationships", flush=True)
        if name == "symbols":
            # Whole-crate Mermaid layouts are unwieldy. Partition by actual
            # lexical ownership, retaining all nodes and every outgoing relationship.
            for module, subset in module_diagrams(graph):
                filename = Path("by-module") / (module.replace("::", "--") + ".mmd")
                diagrams.append((module, filename, subset, command))
        else:
            diagrams.append((name, Path(f"{name}.mmd"), graph, command))
    for name, filename, graph, command in diagrams:
        target = output / filename
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(mermaid(graph, command, name))
    version = subprocess.run(
        ["cargo", "modules", "--version"], cwd=ROOT, text=True, stdout=subprocess.PIPE, check=True,
    ).stdout.strip()
    documentation = [
        "# Autogenerated Nacre UML dependency diagrams", "",
        f"Generated with `{version}` from the current source, including private symbols.", "",
        "Regenerate from the repository root:", "", "```sh",
        "python3 scripts/generate_uml.py --render", "```", "",
        "Requirements: cargo-modules, Graphviz (`dot`), and Mermaid CLI (`mmdc`) for rendering.", "",
        "| View | Symbols | Relationships |", "| --- | ---: | ---: |",
    ]
    for name, nodes, edges, _ in results:
        link = "symbols.dot" if name == "symbols" else f"{name}.mmd"
        documentation.append(f"| [{name}]({link}) | {nodes} | {edges} |")
    documentation += [
        "", "Open `.mmd` source in Mermaid; rendered `.svg` files open directly in a browser.",
        "The complete symbol graph is split automatically by Rust module for Mermaid performance.",
        "Every original relationship appears in its source module's diagram; referenced symbols",
        "are repeated where needed. No symbol or relationship is discarded.",
        "The unpartitioned graph is retained as `symbols.dot`; `--render` also produces",
        "`symbols.graphviz.svg` for browsing the complete graph.", "",
        "These are source-symbol dependency diagrams, not reconstructed class-field layouts.",
        "`declares` is lexical containment, not object ownership; `uses` is the analyzer's static dependency.",
        "Library views exclude external/sysroot symbols. The CLI view retains referenced library APIs.",
        "The normal Cargo configuration is analyzed; test-only/disabled-feature code, C template internals,",
        "and JavaScript/Python/editor-extension internals are not included.", "",
        "## Module detail diagrams", "",
    ]
    documentation += [f"- [{name}]({filename.as_posix()})" for name, filename, _, _ in diagrams if filename.parent != Path(".")]
    documentation += ["", "## Exact extraction commands", ""]
    documentation += [f"- `{command}`" for _, _, _, command in results]
    (output / "README.md").write_text("\n".join(documentation) + "\n")
    if args.render:
        for _, filename, _, _ in diagrams:
            subprocess.run([
                "mmdc", "-i", str(output / filename),
                "-o", str((output / filename).with_suffix(".svg")),
            ], check=True)
        subprocess.run([
            "dot", "-Kdot", "-Tsvg", str(output / "symbols.dot"),
            "-o", str(output / "symbols.graphviz.svg"),
        ], check=True)


if __name__ == "__main__":
    main()
