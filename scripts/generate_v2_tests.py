#!/usr/bin/env python3
"""Regenerate the checked-in Rust tests from tests/v2-cases.json. No dependencies."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def quoted(text):
    return json.dumps(text, ensure_ascii=False)

def sources():
    cases = json.loads((ROOT / "tests/v2-cases.json").read_text())
    frontend = ['// Generated by scripts/generate_v2_tests.py; edit tests/v2-cases.json.\n',
                'use nacre::validate;\n']
    native = ['// Generated by scripts/generate_v2_tests.py; edit tests/v2-cases.json.\n',
              'use nacre::{compile_to_c, native};\n']
    native += [
        '\nfn assert_memory_balanced(stderr: &[u8]) {\n',
        '    let report = String::from_utf8_lossy(stderr);\n',
        '    let mut fields = report.split_whitespace();\n',
        '    assert_eq!(fields.next(), Some("NACRE_MEMORY"), "{report}");\n',
        '    let allocations = fields.next().unwrap().strip_prefix("allocations=").unwrap();\n',
        '    let frees = fields.next().unwrap().strip_prefix("frees=").unwrap();\n',
        '    assert_eq!(allocations, frees, "{report}");\n',
        '    assert_eq!(fields.next(), Some("live=0"), "{report}");\n',
        '    assert_eq!(fields.next(), None, "{report}");\n',
        '}\n',
    ]
    for c in cases:
        frontend += [f'\n#[test]\nfn {c["name"]}() {{\n', f'    let source = {quoted(c["source"])};\n']
        if c['valid']:
            frontend += ['    validate(source).unwrap_or_else(|e| panic!("{}", e.render("case.ncr", source)));\n']
        else:
            frontend += ['    let _error = validate(source).expect_err("invalid source accepted");\n']
            if c.get('error', '').startswith('E'):
                frontend += [f'    assert!(_error.message.contains({quoted(c.get("error", ""))}), "{{}}", _error.render("case.ncr", source));\n']
        frontend += ['}\n']
        if 'stdout' in c:
            native += [f'\n#[test]\nfn {c["name"]}() {{\n', f'    let source = {quoted(c["source"])};\n',
                       '    let c = compile_to_c(source).unwrap_or_else(|e| panic!("{}", e.render("case.ncr", source)));\n',
                       '    let program = native::compile_c_with_flags(&c, &["-DNACRE_MEMORY_STATS"]).unwrap();\n',
                       '    let result = program.output().unwrap();\n',
                       '    assert!(result.status.success(), "{}", String::from_utf8_lossy(&result.stderr));\n',
                       f'    assert_eq!(result.stdout, {quoted(c["stdout"])}.as_bytes());\n',
                       '    assert_memory_balanced(&result.stderr);\n', '}\n']
    return {'ownership_frontend.rs': ''.join(frontend), 'ownership_native.rs': ''.join(native)}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in sources().items():
        path = ROOT / 'tests' / name
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Outdated generated test file: {path}')
        else:
            path.write_text(content)
    print('V2 test sources are in sync.' if args.check else 'V2 test sources generated.')

if __name__ == '__main__':
    main()
