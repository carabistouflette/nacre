#!/usr/bin/env python3
"""Regenerate the checked-in Rust tests from tests/v5-cases.json. No dependencies."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def quoted(text):
    # JSON's \u0000 is not a Rust escape; convert actual control characters.
    out = json.dumps(text, ensure_ascii=False)
    return out.replace("\\u0000", "\\0")

def sources():
    cases = json.loads((ROOT / "tests/v5-cases.json").read_text())
    frontend = ['// Generated by scripts/generate_v5_tests.py; edit tests/v5-cases.json.\n',
                'use nacre::validate;\n']
    native = ['// Generated by scripts/generate_v5_tests.py; edit tests/v5-cases.json.\n',
              'use nacre::{compile_to_c, native};\n']
    for c in cases:
        frontend += [f'\n#[test]\nfn {c["name"]}() {{\n', f'    let source = {quoted(c["source"])};\n']
        if c['valid']:
            frontend += ['    validate(source).unwrap_or_else(|e| panic!("{}", e.render("case.ncr", source)));\n']
        else:
            frontend += ['    let _error = validate(source).expect_err("invalid source accepted");\n']
            if c['error'].startswith('E'):
                frontend += [f'    assert!(_error.message.contains({quoted(c["error"])}), "{{}}", _error.render("case.ncr", source));\n']
        frontend += ['}\n']
        if 'stdout' in c:
            count = c['allocations']
            stats = f'NACRE_MEMORY allocations={count} frees={count} live=0\n'
            native += [f'\n#[test]\nfn {c["name"]}() {{\n', f'    let source = {quoted(c["source"])};\n',
                       '    let c = compile_to_c(source).unwrap_or_else(|e| panic!("{}", e.render("case.ncr", source)));\n',
                       '    let program = native::compile_c_with_flags(&c, &["-DNACRE_MEMORY_STATS"]).unwrap();\n',
                       '    let result = program.output().unwrap();\n',
                       '    assert!(result.status.success(), "{}", String::from_utf8_lossy(&result.stderr));\n',
                       f'    assert_eq!(result.stdout, {quoted(c["stdout"])}.as_bytes());\n',
                       f'    assert_eq!(result.stderr, {quoted(stats)}.as_bytes());\n', '}\n']
        if 'runtime_error' in c:
            native += [f'\n#[test]\nfn {c["name"]}() {{\n', f'    let source = {quoted(c["source"])};\n',
                       '    let c = compile_to_c(source).unwrap();\n',
                       '    let program = native::compile_c(&c).unwrap();\n',
                       '    let result = program.output().unwrap();\n',
                       '    assert_eq!(result.status.code(), Some(70));\n',
                       '    assert!(String::from_utf8_lossy(&result.stderr).contains("[1:"));\n', '}\n']
    return {'features_v5_frontend.rs': ''.join(frontend), 'features_v5_native.rs': ''.join(native)}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in sources().items():
        path = ROOT / 'tests' / name
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Outdated generated test file: {path}')
        else:
            path.write_text(content)
    print('V5 test sources are in sync.' if args.check else 'V5 test sources generated.')

if __name__ == '__main__':
    main()
