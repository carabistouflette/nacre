#!/usr/bin/env python3
"""Check exact C runtime plus HANDWRITTEN object/drop fixture.

This does NOT validate the Rust compiler or its generated code.
Use validate.py for real end-to-end checks when Rust is available.
"""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
ROOT = Path(__file__).resolve().parents[1]

def check(cc):
    source = (ROOT / "src/runtime.c").read_text() + "\n" + (ROOT / "tests/fixtures/object_support.c").read_text()
    with tempfile.TemporaryDirectory(prefix="nacre-c-support-") as d:
        c, exe = Path(d) / "fixture.c", Path(d) / "fixture"
        c.write_text(source)
        flags = ["-std=c11", "-O1", "-g", "-DNACRE_MEMORY_STATS", "-fsanitize=address,undefined", "-fno-sanitize-recover=all", "-fno-omit-frame-pointer"]
        subprocess.run([cc, *flags, str(c), "-o", str(exe)], check=True, capture_output=True)
        env = dict(os.environ, ASAN_OPTIONS="detect_leaks=1:halt_on_error=1")
        result = subprocess.run([str(exe)], capture_output=True, env=env, check=True)
        assert result.stdout == b"", result.stdout
        assert result.stderr == b"NACRE_MEMORY allocations=20010 frees=20010 live=0\n", result.stderr
    return {"compiler": cc, "fixture": "handwritten C, not generated by Rust", "allocations": 20010,
            "frees": 20010, "live_at_exit": 0, "asan_ubsan_lsan": "passed"}

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--cc", action="append", default=[])
    args = p.parse_args()
    compilers = args.cc or [c for c in ("gcc", "clang") if shutil.which(c)]
    if not compilers:
        raise SystemExit("GCC/Clang manquant")
    print(json.dumps({"scope": "C support only, not compiler validation", "results": [check(c) for c in compilers]}, indent=2))

if __name__ == "__main__":
    main()
