//! C11 backend. Each expression is sequenced into temporaries, preserving
//! left-to-right evaluation. && and || become conditional blocks.
use crate::ast::{BinaryOp as B, UnaryOp};
use crate::diagnostic::line_column;
use crate::ir::{self as t, CallTarget, Place, PlaceKind, Type};
use crate::c_repr::{ctype, ctype_param, object_zero};
use std::fmt::Write;

const TEMPORARY_PREFIX: &str = "ncr_t_";

pub fn generate(program: &t::Program, source: &str) -> String {
    let mut emitter = Emitter { program, source, output: String::new(), indent: 0, next_temp: 0, literals: Vec::new(), owners: Vec::new(), temporary_owners: Vec::new(), loops: Vec::new() };
    for function in &program.functions { emitter.function(function); }
    let mut out = format!("/* Generated by Nacre {}. Do not edit this file as source. */\n", env!("CARGO_PKG_VERSION"));
    out.push_str(include_str!("runtime.c"));
    out.push_str("\n/* Process arguments belong to the generated executable, not standalone runtime fixtures. */\nstatic int ncr_argc;\nstatic char **ncr_argv;\n");
    out.push_str(&crate::stdlib_codegen::preamble(program));
    out.push_str(&class_support(program));
    out.push_str("\n/* UTF-8 string literals, with static lifetime. */\n");
    for (i, text) in emitter.literals.iter().enumerate() {
        write!(out, "static const unsigned char ncr_lit_{i}[] = {{").unwrap();
        for byte in text.as_bytes() { write!(out, "{byte},").unwrap(); }
        out.push_str("0};\n");
    }
    out.push_str("\n/* Prototypes support recursion and forward calls. */\n");
    for function in &program.functions {
        if crate::stdlib_codegen::should_emit_prototype(program, function) {
            writeln!(out, "{};", signature(program, function)).unwrap();
        }
    }
    out.push('\n');
    out.push_str(&crate::stdlib_codegen::implementations(program));
    out.push_str(&interface_implementations(program));
    out.push_str(&emitter.output);
    writeln!(out, "int main(int argc, char **argv) {{\n    ncr_argc = argc;\n    ncr_argv = argv;\n    ncr_fn_{}();\n    ncr_memory_report();\n    return 0;\n}}", program.main).unwrap();
    out
}
fn cast_expression(target: Type, source: Type, value: &str, line: usize, column: usize) -> String {
    let checked = |name: &str| format!("{name}({value}, {line}, {column})");
    match target {
        Type::Byte => match source {
            Type::Byte => value.to_owned(),
            Type::Char => checked("ncr_cast_byte_u32"),
            Type::Int => checked("ncr_cast_byte_i32"),
            Type::Long => checked("ncr_cast_byte_i64"),
            Type::Double => checked("ncr_cast_byte_f64"),
            _ => unreachable!("checked numeric cast source"),
        },
        Type::Char => match source {
            Type::Byte => format!("((uint32_t){value})"),
            Type::Char => value.to_owned(),
            Type::Int => checked("ncr_cast_char_i32"),
            Type::Long => checked("ncr_cast_char_i64"),
            Type::Double => checked("ncr_cast_char_f64"),
            _ => unreachable!("checked numeric cast source"),
        },
        Type::Int => match source {
            Type::Byte | Type::Char => format!("((int32_t){value})"),
            Type::Int => value.to_owned(),
            Type::Long => checked("ncr_cast_i32_i64"),
            Type::Double => checked("ncr_cast_i32_f64"),
            _ => unreachable!("checked numeric cast source"),
        },
        Type::Long => match source {
            Type::Byte | Type::Char | Type::Int => format!("((int64_t){value})"),
            Type::Long => value.to_owned(),
            Type::Double => checked("ncr_cast_i64_f64"),
            _ => unreachable!("checked numeric cast source"),
        },
        Type::Double => match source {
            Type::Byte | Type::Char | Type::Int | Type::Long => format!("((double){value})"),
            Type::Double => value.to_owned(),
            _ => unreachable!("checked numeric cast source"),
        },
        _ => unreachable!("checked numeric cast target"),
    }
}
fn zero_value(program: &t::Program, ty: Type) -> String {
    match ty {
        Type::Object(class) => object_zero(program, class),
        Type::Borrow { .. } => "NULL".to_owned(),
        Type::Byte | Type::Unit => "UINT8_C(0)".to_owned(),
        Type::Char => "UINT32_C(0)".to_owned(),
        Type::Int => "INT32_C(0)".to_owned(),
        Type::Long => "INT64_C(0)".to_owned(),
        Type::Double => "0.0".to_owned(),
        Type::Boolean => "false".to_owned(),
        Type::String => "{NULL, 0}".to_owned(),
        Type::Void => unreachable!("checked local type"),
    }
}


fn signature(program: &t::Program, function: &t::Function) -> String {
    let mut params = Vec::new();
    if let Some(class) = function.receiver {
        let receiver_ty = if program.classes[class].is_interface || program.classes[class].variants.is_some() {
            format!("{} ncr_self", ctype(program, Type::Object(class)))
        } else {
            format!("ncr_obj_{class} *restrict ncr_self")
        };
        params.push(receiver_ty);
    }
    for (id, ty) in &function.params { params.push(format!("{} ncr_v_{id}", ctype_param(program, *ty))); }
    if function.native.is_some() { params.extend(["size_t ncr_line".to_owned(), "size_t ncr_column".to_owned()]); }
    let params = if params.is_empty() { "void".to_owned() } else { params.join(", ") };
    format!("static inline {} ncr_fn_{}({params})", ctype(program, function.return_type), function.id)
}
fn enum_order(program: &t::Program) -> Vec<usize> {
    fn visit(id: usize, program: &t::Program, states: &mut [u8], order: &mut Vec<usize>) {
        if states[id] == 2 || states[id] == 1 { return; }
        states[id] = 1;
        if let Some(variants) = &program.classes[id].variants {
            for field in variants.iter().flat_map(|variant| &variant.fields) {
                if let Type::Object(child) = field
                    && program.classes[*child].variants.is_some() {
                        visit(*child, program, states, order);
                    }
            }
        }
        states[id] = 2;
        order.push(id);
    }
    let mut states = vec![0; program.classes.len()];
    let mut order = Vec::new();
    for class in &program.classes {
        if class.variants.is_some() { visit(class.id, program, &mut states, &mut order); }
    }
    order
}
fn class_support(program: &t::Program) -> String {
    let mut out = String::from("\n/* By-value tagged sums and allocation-free interface representations. */\n");
    for class in &program.classes {
        out.push_str(&format!("typedef struct ncr_obj_{} ncr_obj_{};\n", class.id, class.id));
    }
    for class in &program.classes {
        if matches!(class.native, Some(t::NativeClass::Map { .. })) {
            out.push_str(&format!("struct ncr_map_entry_{};\n", class.id));
        }
    }
    for class in &program.classes {
        if matches!(class.native, Some(t::NativeClass::OrderedMap(_, _))) {
            out.push_str(&format!("struct ncr_ordered_entry_{};\n", class.id));
        }
    }
    for class in &program.classes {
        if matches!(class.native, Some(t::NativeClass::OrderedMap(_, _))) {
            out.push_str(&crate::stdlib_codegen::ordered_storage_definition(program, class.id));
        }
    }
    for class in &program.classes {
        if class.is_interface {
            out.push_str(&format!("struct ncr_obj_{0} {{ void *data; const struct ncr_vtable_{0} *vtable; }};\n", class.id));
        }
    }
    // Set embeds the table control record from its hidden Map<K, Unit>
    // specialization. A custom table embeds its owned Hasher interface value.
    for class in &program.classes {
        if let Some(t::NativeClass::Map { hasher, .. }) = class.native {
            out.push_str(&crate::stdlib_codegen::hash_table_definition(program, class.id, hasher));
        }
    }
    for id in enum_order(program) {
        let class = &program.classes[id];
        out.push_str(&format!("struct ncr_obj_{id} {{\n    int32_t tag;\n    union {{\n"));
        for (variant_id, variant) in class.variants.as_ref().unwrap().iter().enumerate() {
            out.push_str("        struct {\n");
            if variant.fields.is_empty() {
                out.push_str("            unsigned char ncr_empty;\n");
            }
            for (field_id, ty) in variant.fields.iter().enumerate() {
                out.push_str(&format!("            {} f{field_id};\n", ctype(program, *ty)));
            }
            out.push_str(&format!("        }} v{variant_id};\n"));
        }
        out.push_str("    } data;\n};\n");
    }
    for class in &program.classes {
        if class.is_interface || class.variants.is_some() { continue; }
        out.push_str(&format!("struct ncr_obj_{} {{\n", class.id));
        if let Some(native) = class.native { out.push_str(&crate::stdlib_codegen::fields(program, native, class.id)); }
        else if class.fields.is_empty() { out.push_str("    unsigned char ncr_empty;\n"); }
        for (id, ty) in class.fields.iter().enumerate() { out.push_str(&format!("    {} ncr_f_{id};\n", ctype(program, *ty))); }
        out.push_str("};\n");
    }
    for class in &program.classes {
        if !class.is_interface { continue; }
        out.push_str(&format!("struct ncr_vtable_{} {{\n    void (*destroy)(void *);\n", class.id));
        for (slot, id) in class.interface_methods.iter().enumerate() {
            let method = &program.functions[*id];
            let mut params = vec![std::borrow::Cow::Borrowed("void *")];
            params.extend(method.params.iter().map(|(_, ty)| ctype(program, *ty)));
            out.push_str(&format!("    {} (*m{slot})({});\n", ctype(program, method.return_type), params.join(", ")));
        }
        out.push_str("};\n");
    }
    // Native iterator factories construct interfaces before their typed
    // vtable definitions are emitted.
    for class in &program.classes {
        for (interface, _) in &class.implementations {
            out.push_str(&format!(
                "static const struct ncr_vtable_{interface} ncr_vtable_{}_{};\n",
                class.id, interface,
            ));
        }
    }
    // Hash entries embed V by value, so define them after all object, enum,
    // interface, and vtable layouts, but before native drop bodies.
    for class in &program.classes {
        if let Some(t::NativeClass::Map { key, value, .. }) = class.native {
            out.push_str(&crate::stdlib_codegen::map_entry_definition(program, class.id, key, value));
        }
    }
    for class in &program.classes {
        if let Some(t::NativeClass::OrderedMap(key, value)) = class.native {
            out.push_str(&crate::stdlib_codegen::ordered_entry_definition(program, class.id, key, value));
        }
    }
    for class in &program.classes {
        out.push_str(&format!("static void ncr_drop_{}({} p);\n", class.id, ctype(program, Type::Object(class.id))));
    }
    out.push_str(&crate::stdlib_codegen::drop_helper_prototypes(program));
    for class in &program.classes {
        out.push_str(&format!("static void ncr_drop_{}({} p) {{\n", class.id, ctype(program, Type::Object(class.id))));
        if class.is_interface {
            out.push_str("    if (p.data != NULL) { p.vtable->destroy(p.data); }\n");
        } else if let Some(variants) = &class.variants {
            out.push_str("    if (p.tag == -1) { return; }\n    switch (p.tag) {\n");
            for (variant_id, variant) in variants.iter().enumerate() {
                out.push_str(&format!("    case {variant_id}:"));
                for (field_id, ty) in variant.fields.iter().enumerate().rev() {
                    if let Type::Object(child) = ty {
                        out.push_str(&format!("\n        ncr_drop_{child}(p.data.v{variant_id}.f{field_id});"));
                    }
                }
                out.push_str("\n        break;\n");
            }
            out.push_str("    default: break;\n    }\n    p.tag = -1;\n");
        } else {
            out.push_str("    if (p == NULL) { return; }\n");
            for (id, ty) in class.fields.iter().enumerate().rev() {
                if let Type::Object(child) = ty { out.push_str(&format!("    ncr_drop_{child}(p->ncr_f_{id});\n")); }
            }
            if let Some(native) = class.native { out.push_str(&crate::stdlib_codegen::drop_fields(program, native, class.id)); }
            out.push_str("    ncr_deallocate(p);\n");
        }
        out.push_str("}\n");
    }
    out
}
fn interface_implementations(program: &t::Program) -> String {
    let mut out = String::from("\n/* Typed adapter functions: no incompatible function-pointer casts. */\n");
    for class in &program.classes {
        for (interface, methods) in &class.implementations {
            let cid = class.id;
            out.push_str(&format!("static void ncr_destroy_{cid}_{interface}(void *p) {{ ncr_drop_{cid}((ncr_obj_{cid} *)p); }}\n"));
            for (slot, implementation) in methods.iter().enumerate() {
                let method = &program.functions[*implementation];
                let mut params = vec!["void *ncr_data".to_owned()];
                let mut args = vec![format!("(ncr_obj_{cid} *)ncr_data")];
                for (index, (_, ty)) in method.params.iter().enumerate() {
                    params.push(format!("{} a{index}", ctype(program, *ty)));
                    args.push(format!("a{index}"));
                }
                if method.native.is_some() {
                    // The interface ABI has no source coordinates; zero marks an unknown call site.
                    args.extend(["0".to_owned(), "0".to_owned()]);
                }
                out.push_str(&format!("static {} ncr_thunk_{cid}_{interface}_{slot}({}) {{\n    {}ncr_fn_{implementation}({});\n}}\n",
                    ctype(program, method.return_type), params.join(", "),
                    if method.return_type == Type::Void { "" } else { "return " }, args.join(", ")));
            }
            out.push_str(&format!("static const struct ncr_vtable_{interface} ncr_vtable_{cid}_{interface} = {{\n    .destroy = ncr_destroy_{cid}_{interface},\n"));
            for slot in 0..methods.len() { out.push_str(&format!("    .m{slot} = ncr_thunk_{cid}_{interface}_{slot},\n")); }
            out.push_str("};\n");
        }
    }
    out
}

fn place_text(place: &Place) -> String {
    match &place.kind {
        PlaceKind::Var(id) => format!("ncr_v_{id}"),
        PlaceKind::This => "ncr_self".to_owned(),
        PlaceKind::Field { base, field } => format!("({})->ncr_f_{field}", place_text(base)),
    }
}

struct Emitter<'a> {
    program: &'a t::Program,
    source: &'a str, output: String, indent: usize, next_temp: usize, literals: Vec<String>,
    owners: Vec<Vec<(usize, usize)>>, // lexical scopes of (variable ID, class ID)
    temporary_owners: Vec<(usize, usize)>, // fresh temporary ID and class ID until ownership transfers
    loops: Vec<usize>,              // first scope cleaned by break/continue
}

impl Emitter<'_> {
    fn line(&mut self, text: &str) {
        self.output.push_str(&"    ".repeat(self.indent));
        self.output.push_str(text);
        self.output.push('\n');
    }
    fn fresh(&mut self) -> String {
        let name = format!("{TEMPORARY_PREFIX}{}", self.next_temp);
        self.next_temp += 1;
        name
    }
    fn bind(&mut self, ty: Type, value: &str) -> String {
        let name = self.fresh();
        self.line(&format!("{} {name} = {value};", ctype(self.program, ty)));
        name
    }
    fn bind_owned(&mut self, ty: Type, value: &str) -> String {
        let id = self.next_temp;
        let name = self.bind(ty, value);
        if let Type::Object(class) = ty { self.temporary_owners.push((id, class)); }
        name
    }
    fn consume_temporary(&mut self, ty: Type, value: &str) {
        let Type::Object(class) = ty else { return; };
        let id = value.strip_prefix(TEMPORARY_PREFIX).and_then(|suffix| suffix.parse::<usize>().ok())
            .expect("an owned expression returns a generated temporary");
        let index = self.temporary_owners.iter()
            .position(|(temporary, owner)| *temporary == id && *owner == class)
            .expect("an owned expression temporary remains in the ownership ledger");
        self.temporary_owners.remove(index);
    }
    fn drop_value(&mut self, class: usize, value: &str) {
        self.line(&format!("ncr_drop_{class}({value});"));
    }
    fn cleanup_temporaries(&mut self) {
        let mut index = self.temporary_owners.len();
        while index > 0 {
            index -= 1;
            let (temporary, class) = self.temporary_owners[index];
            self.drop_value(class, &format!("{TEMPORARY_PREFIX}{temporary}"));
            self.line(&format!("{TEMPORARY_PREFIX}{temporary} = {};", object_zero(self.program, class)));
        }
    }
    fn cleanup_from(&mut self, first: usize) {
        // Clone the small list to avoid mutating output while borrowing scopes.
        let owners: Vec<_> = self.owners[first..].iter().rev().flat_map(|s| s.iter().rev().copied()).collect();
        for (id, class) in owners {
            self.drop_value(class, &format!("ncr_v_{id}"));
            self.line(&format!("ncr_v_{id} = {};", object_zero(self.program, class)));
        }
    }
    fn function(&mut self, function: &t::Function) {
        if function.native.is_some() { return; }
        if let Some(slot) = function.virtual_slot {
            self.line(&format!("{} {{", signature(self.program, function)));
            let mut args = vec!["ncr_self.data".to_owned()];
            args.extend(function.params.iter().map(|(id, _)| format!("ncr_v_{id}")));
            self.line(&format!("    {}ncr_self.vtable->m{slot}({});",
                if function.return_type == Type::Void { "" } else { "return " }, args.join(", ")));
            self.line("}\n");
            return;
        }
        self.next_temp = 0;
        self.owners.clear(); self.temporary_owners.clear(); self.loops.clear();
        self.owners.push(function.params.iter().filter_map(|(id, ty)| {
            if let Type::Object(class) = ty { Some((*id, *class)) } else { None }
        }).collect());
        self.line(&format!("{} {{", signature(self.program, function)));
        self.indent += 1;
        self.block(&function.body);
        self.cleanup_temporaries();
        self.cleanup_from(0);
        if function.return_type == Type::Void { self.line("return;"); }
        self.indent -= 1;
        self.line("}\n");
        self.owners.pop();
    }
    fn block(&mut self, block: &t::Block) {
        self.owners.push(Vec::new());
        for stmt in block { self.statement(stmt); }
        self.cleanup_from(self.owners.len() - 1);
        self.owners.pop();
    }
    fn statement(&mut self, stmt: &t::Stmt) {
        match stmt {
            t::Stmt::Let { id, ty, value } => {
                // Internal zeroes make conditional lexical cleanup safe. The
                // ownership CFG still rejects reads before source initialization.
                let initializer_type = value.as_ref().map(|value| value.ty);
                let value = value.as_ref().map(|value| self.expression(value))
                    .unwrap_or_else(|| zero_value(self.program, *ty));
                self.line(&format!("{} ncr_v_{id} = {value};", ctype(self.program, *ty)));
                if let Type::Object(class) = ty {
                    self.owners.last_mut().unwrap().push((*id, *class));
                    if initializer_type.is_some() { self.consume_temporary(*ty, &value); }
                }
            }
            t::Stmt::Assign { target, value } => {
                // Receiver evaluation precedes RHS evaluation. Its root is
                // locked by the checker, so no RHS call can free this object.
                let target_text = if let PlaceKind::Field { base, field } = &target.kind {
                    let base = self.bind(base.ty, &place_text(base));
                    format!("({base})->ncr_f_{field}")
                } else { place_text(target) };
                let value = self.expression(value);
                if let Type::Object(class) = target.ty { self.drop_value(class, &target_text); }
                self.line(&format!("{target_text} = {value};"));
                self.consume_temporary(target.ty, &value);
            }
            t::Stmt::Expr(expr) => {
                let value = self.expression(expr);
                if let Type::Object(class) = expr.ty {
                    self.drop_value(class, &value);
                    self.consume_temporary(expr.ty, &value);
                } else if !value.is_empty() { self.line(&format!("(void){value};")); }
            }
            t::Stmt::If { condition, then_block, else_block } => {
                let condition = self.expression(condition);
                self.line(&format!("if ({condition}) {{"));
                self.indent += 1;
                self.block(then_block);
                self.indent -= 1;
                if let Some(else_block) = else_block {
                    self.line("} else {");
                    self.indent += 1;
                    self.block(else_block);
                    self.indent -= 1;
                }
                self.line("}");
            }
            t::Stmt::While { condition, body } => {
                self.line("while (true) {");
                self.indent += 1;
                // This must remain inside the loop: continue recomputes it.
                let condition = self.expression(condition);
                self.line(&format!("if (!{condition}) {{ break; }}"));
                self.loops.push(self.owners.len());
                self.block(body);
                self.loops.pop();
                self.indent -= 1;
                self.line("}");
            }
            t::Stmt::Match { value, arms } => {
                let value_type = value.ty;
                let class = value_type.object_class().expect("typed enum match");
                let borrow_mode = match value_type { Type::Borrow { mutable, .. } => Some(mutable), _ => None };
                let borrowed = borrow_mode.is_some();
                let value = self.expression(value);
                let member = if borrowed { format!("({value})->") } else { format!("{value}.") };
                for (index, arm) in arms.iter().enumerate() {
                    self.line(&format!("{} ({member}tag == {}) {{",
                        if index == 0 { "if" } else { "else if" }, arm.variant));
                    self.indent += 1;
                    if !borrowed {
                        self.line(&format!("{value}.tag = -1; /* active payload transferred */"));
                    }
                    self.owners.push(Vec::new());
                    let field_count = self.program.classes[class].variants.as_ref().unwrap()[arm.variant].fields.len();
                    for field in 0..field_count {
                        let ty = self.program.classes[class].variants.as_ref().unwrap()[arm.variant].fields[field];
                        let payload = format!("{member}data.v{}.f{field}", arm.variant);
                        if let Some(id) = arm.bindings.get(field) {
                            let binding_type = match (ty, borrow_mode) {
                                (Type::Object(class), Some(mutable)) => Type::Borrow { class, mutable },
                                _ => ty,
                            };
                            let initializer = if borrowed && matches!(ty, Type::Object(owner) if self.program.classes[owner].variants.is_some()) {
                                format!("&({payload})")
                            } else { payload };
                            self.line(&format!("{} ncr_v_{id} = {initializer};", ctype(self.program, binding_type)));
                            if !borrowed
                                && let Type::Object(owner) = ty {
                                    self.owners.last_mut().unwrap().push((*id, owner));
                                }
                        } else if !borrowed
                            && let Type::Object(owner) = ty { self.drop_value(owner, &payload); }
                    }
                    self.block(&arm.body);
                    self.cleanup_from(self.owners.len() - 1);
                    self.owners.pop();
                    self.indent -= 1;
                    self.line("}");
                }
                self.line("else {");
                self.indent += 1;
                if !borrowed { self.drop_value(class, &value); }
                self.line("abort();");
                self.indent -= 1;
                self.line("}");
                if !borrowed { self.consume_temporary(value_type, &value); }
            }
            t::Stmt::Return(value) => {
                let value = value.as_ref().map(|value| {
                    let result = self.expression(value);
                    self.consume_temporary(value.ty, &result);
                    result
                });
                self.cleanup_temporaries();
                self.cleanup_from(0);
                if let Some(value) = value { self.line(&format!("return {value};")); }
                else { self.line("return;"); }
            }
            t::Stmt::Break => {
                self.cleanup_from(*self.loops.last().expect("checked loop"));
                self.line("break;");
            }
            t::Stmt::Continue => {
                self.cleanup_from(*self.loops.last().expect("checked loop"));
                self.line("continue;");
            }
            t::Stmt::Block(block) => {
                self.line("{"); self.indent += 1;
                self.block(block);
                self.indent -= 1; self.line("}");
            }
        }
    }
    // An empty result is used only for void calls, never as a C expression.
    fn expression(&mut self, expr: &t::Expr) -> String {
        use t::ExprKind as E;
        match &expr.kind {
            E::Char(value) => self.bind(Type::Char, &format!("UINT32_C({})", *value as u32)),
            E::Int(n) => {
                let value = if *n == i32::MIN { "INT32_MIN".to_owned() } else { format!("INT32_C({n})") };
                self.bind(Type::Int, &value)
            }
            E::Long(value) => {
                let value = if *value == i64::MIN { "INT64_MIN".to_owned() } else { format!("INT64_C({value})") };
                self.bind(Type::Long, &value)
            }
            E::Double(value) => self.bind(Type::Double, &format!("{value:.17e}")),
            E::Unit => self.bind(Type::Unit, "UINT8_C(0)"),
            E::Boolean(value) => self.bind(Type::Boolean, if *value { "true" } else { "false" }),
            E::String(text) => {
                let id = self.literals.len();
                self.literals.push(text.clone());
                self.bind(Type::String, &format!("{{ncr_lit_{id}, {}}}", text.len()))
            }
            E::Cast { value } => {
                let source_type = value.ty;
                let value = self.expression(value);
                let (line, column) = line_column(self.source, expr.span.start);
                let cast = cast_expression(expr.ty, source_type, &value, line, column);
                self.bind(expr.ty, &cast)
            }
            E::Read(place) => self.bind(expr.ty, &place_text(place)),
            E::Borrow { place, .. } => {
                let target = expr.ty.object_class().expect("borrow target");
                let concrete = place.ty.object_class().expect("borrow source");
                if target == concrete {
                    let value = place_text(place);
                    if place.ty.is_object() && self.program.classes[concrete].variants.is_some() {
                        self.bind(expr.ty, &format!("&({value})"))
                    } else { self.bind(expr.ty, &value) }
                }
                else { self.bind(expr.ty, &format!("(ncr_obj_{target}){{(void *){}, &ncr_vtable_{concrete}_{target}}}", place_text(place))) }
            }
            E::MapCapacity(map) => {
                let map = place_text(map);
                let capacity = crate::stdlib_codegen::map_capacity_expression(&map);
                self.bind(expr.ty, &capacity)
            }
            E::MapSlot { map, index, kind, .. } => {
                let index = self.expression(index);
                let map_text = place_text(map);
                let map_class = map.ty.object_class().expect("map-slot receiver is an object");
                let slot = crate::stdlib_codegen::map_slot_expression(
                    self.program, map_class, &map_text, &index, *kind, expr.ty);
                self.bind(expr.ty, &slot)
            }
            E::Upcast { value, interface, concrete } => {
                let value_type = value.ty;
                let value = self.expression(value);
                let result = self.bind_owned(expr.ty, &format!("(ncr_obj_{interface}){{(void *){value}, &ncr_vtable_{concrete}_{interface}}}"));
                self.consume_temporary(value_type, &value);
                result
            }
            E::Move(id) => {
                let value = self.bind_owned(expr.ty, &format!("ncr_v_{id}"));
                let class = expr.ty.object_class().expect("owning move");
                self.line(&format!("ncr_v_{id} = {}; /* ownership transferred */", object_zero(self.program, class)));
                value
            }
            E::Drop(inner) => {
                let value = self.expression(inner);
                let Type::Object(class) = inner.ty else { unreachable!("checked drop type") };
                self.drop_value(class, &value);
                self.consume_temporary(inner.ty, &value);
                String::new()
            }
            E::New { class, constructor, args } => {
                let values: Vec<_> = args.iter().map(|arg| self.expression(arg)).collect();
                let (line, column) = line_column(self.source, expr.span.start);
                let result = self.bind_owned(expr.ty, &format!("ncr_allocate(sizeof(ncr_obj_{class}), {line}, {column})"));
                for (arg, value) in args.iter().zip(&values) { self.consume_temporary(arg.ty, value); }
                let mut params = vec![result.clone()];
                params.extend(values);
                if self.program.functions[*constructor].native.is_some() { params.extend([line.to_string(), column.to_string()]); }
                self.line(&format!("ncr_fn_{constructor}({});", params.join(", ")));
                result
            }
            E::Variant { class, variant, args } => {
                let values: Vec<_> = args.iter().map(|arg| self.expression(arg)).collect();
                let fields = &self.program.classes[*class].variants.as_ref().unwrap()[*variant].fields;
                let mut initializer = format!("(ncr_obj_{class}){{.tag = {variant}, .data.v{variant} = {{");
                if fields.is_empty() {
                    initializer.push_str(".ncr_empty = 0");
                } else {
                    for (field, value) in values.iter().enumerate() {
                        if field > 0 { initializer.push_str(", "); }
                        initializer.push_str(&format!(".f{field} = {value}"));
                    }
                }
                initializer.push_str("}}");
                let result = self.bind_owned(expr.ty, &initializer);
                for (arg, value) in args.iter().zip(&values) { self.consume_temporary(arg.ty, value); }
                result
            }
            E::Try { value, return_result } => {
                let Type::Object(source_class) = value.ty else { unreachable!("checked Result carrier") };
                let source = self.program.classes[source_class].result.expect("checked built-in Result carrier");
                let target = self.program.classes[*return_result].result.expect("checked Result return type");
                let carrier = self.expression(value);
                let result = self.bind_owned(expr.ty, &zero_value(self.program, expr.ty));

                self.line(&format!("if ({carrier}.tag == {}) {{", source.ok_variant));
                self.indent += 1;
                self.line(&format!("{result} = {carrier}.data.v{}.f0;", source.ok_variant));
                self.line(&format!("{carrier}.tag = -1; /* success payload transferred */"));
                self.indent -= 1;
                self.line("} else {");
                self.indent += 1;
                let error = self.bind(source.err_type, &format!("{carrier}.data.v{}.f0", source.err_variant));
                self.line(&format!("{carrier}.tag = -1; /* error payload transferred */"));
                self.cleanup_temporaries();
                self.cleanup_from(0);
                let propagated = format!(
                    "(ncr_obj_{return_result}){{.tag = {}, .data.v{} = {{.f0 = {error}}}}}",
                    target.err_variant, target.err_variant);
                self.line(&format!("return {propagated};"));
                self.indent -= 1;
                self.line("}");
                self.consume_temporary(value.ty, &carrier);
                result
            }
            E::Unary { op, expr: inner } => {
                let value = self.expression(inner);
                let operation = match op {
                    UnaryOp::Neg => match expr.ty {
                        Type::Int => format!("ncr_neg({value})"),
                        Type::Long => format!("ncr_long_neg({value})"),
                        Type::Double => format!("(-({value}))"),
                        _ => unreachable!("checked unary negation type"),
                    },
                    UnaryOp::Not => format!("!({value})"),
                    UnaryOp::Plus => value,
                    UnaryOp::BitNot => match expr.ty {
                        Type::Int => format!("ncr_i32_not({value})"),
                        Type::Long => format!("ncr_i64_not({value})"),
                        _ => unreachable!("checked bitwise not type"),
                    },
                };
                self.bind(expr.ty, &operation)
            }
            E::Binary { op, left, right } => {
                let left_value = self.expression(left);
                if matches!(op, B::And | B::Or) {
                    let result = self.bind(Type::Boolean, &left_value);
                    let condition = if *op == B::And { result.clone() } else { format!("!{result}") };
                    self.line(&format!("if ({condition}) {{"));
                    self.indent += 1;
                    let right_value = self.expression(right);
                    self.line(&format!("{result} = {right_value};"));
                    self.indent -= 1;
                    self.line("}");
                    return result;
                }
                let right_value = self.expression(right);
                self.binary_operation(expr, *op, &left_value, &right_value, right)
            }
            E::Call { target, receiver, args } => {
                // Borrow receiver first, then evaluate arguments in source order.
                let mut values = Vec::new();
                if let Some(receiver) = receiver { values.push(self.bind(receiver.ty, &place_text(receiver))); }
                for arg in args { values.push(self.expression(arg)); }
                let call = match target {
                    CallTarget::Function(id) => {
                        if self.program.functions[*id].native.is_some() {
                            let (line, column) = line_column(self.source, expr.span.start);
                            values.extend([line.to_string(), column.to_string()]);
                        }
                        format!("ncr_fn_{id}({})", values.join(", "))
                    },
                    CallTarget::Println => {
                        let name = match args[0].ty {
                            Type::Byte => "ncr_print_byte",
                            Type::Char => "ncr_print_char",
                            Type::Int => "ncr_print_int",
                            Type::Long => "ncr_print_long",
                            Type::Double => "ncr_print_double",
                            Type::Unit => "ncr_print_unit",
                            Type::Boolean => "ncr_print_boolean",
                            Type::String => "ncr_print_string",
                            Type::Void | Type::Object(_) | Type::Borrow { .. } => unreachable!("checked println argument"),
                        };
                        format!("{name}({})", values[0])
                    }
                    CallTarget::Assert => {
                        let cond_val = &values[0];
                        let (line, column) = line_column(self.source, expr.span.start);
                        if values.len() == 2 {
                            let msg_val = &values[1];
                            format!("ncr_assert({cond_val}, {msg_val}.data, {msg_val}.length, {line}, {column})")
                        } else {
                            format!("ncr_assert({cond_val}, (const unsigned char *)\"assertion failed\", 16, {line}, {column})")
                        }
                    }
                };
                let receiver_args = if receiver.is_some() { 1 } else { 0 };
                for (arg, value) in args.iter().zip(values.iter().skip(receiver_args)) {
                    self.consume_temporary(arg.ty, value);
                }
                if expr.ty == Type::Void {
                    self.line(&format!("{call};"));
                    String::new()
                } else if matches!(expr.ty, Type::Object(_)) {
                    self.bind_owned(expr.ty, &call)
                } else {
                    self.bind(expr.ty, &call)
                }
            }
        }
    }

    fn binary_operation(&mut self, expr: &t::Expr, op: B, left_value: &str, right_value: &str, right: &t::Expr) -> String {
        let (line, column) = line_column(self.source, expr.span.start);
        let operation = match op {
            B::Add | B::Sub | B::Mul | B::Div | B::Rem => match expr.ty {
                Type::Double => match op {
                    B::Add => format!("({left_value} + {right_value})"),
                    B::Sub => format!("({left_value} - {right_value})"),
                    B::Mul => format!("({left_value} * {right_value})"),
                    B::Div => format!("({left_value} / {right_value})"),
                    B::Rem => format!("fmod({left_value}, {right_value})"),
                    _ => unreachable!("floating arithmetic operation"),
                },
                Type::Long => match op {
                    B::Add => format!("ncr_long_add({left_value}, {right_value})"),
                    B::Sub => format!("ncr_long_sub({left_value}, {right_value})"),
                    B::Mul => format!("ncr_long_mul({left_value}, {right_value})"),
                    B::Div => {
                        if let t::ExprKind::Long(c) = right.kind && c > 0 {
                            format!("({left_value} / INT64_C({c}))")
                        } else {
                            format!("ncr_long_div({left_value}, {right_value}, {line}, {column})")
                        }
                    }
                    B::Rem => {
                        if let t::ExprKind::Long(c) = right.kind && c > 0 {
                            format!("({left_value} % INT64_C({c}))")
                        } else {
                            format!("ncr_long_rem({left_value}, {right_value}, {line}, {column})")
                        }
                    }
                    _ => unreachable!("long arithmetic operation"),
                },
                Type::Int => match op {
                    B::Add => format!("ncr_add({left_value}, {right_value})"),
                    B::Sub => format!("ncr_sub({left_value}, {right_value})"),
                    B::Mul => format!("ncr_mul({left_value}, {right_value})"),
                    B::Div => {
                        if let t::ExprKind::Int(c) = right.kind && c > 0 {
                            format!("({left_value} / INT32_C({c}))")
                        } else {
                            format!("ncr_div({left_value}, {right_value}, {line}, {column})")
                        }
                    }
                    B::Rem => {
                        if let t::ExprKind::Int(c) = right.kind && c > 0 {
                            format!("({left_value} % INT32_C({c}))")
                        } else {
                            format!("ncr_rem({left_value}, {right_value}, {line}, {column})")
                        }
                    }
                    _ => unreachable!("integer arithmetic operation"),
                },
                _ => unreachable!("checked arithmetic result type"),
            },
            B::Eq => format!("{left_value} == {right_value}"), B::Ne => format!("{left_value} != {right_value}"),
            B::Lt => format!("{left_value} < {right_value}"), B::Le => format!("{left_value} <= {right_value}"),
            B::Gt => format!("{left_value} > {right_value}"), B::Ge => format!("{left_value} >= {right_value}"),
            B::BitAnd | B::BitOr | B::BitXor => match (expr.ty, op) {
                (Type::Int, B::BitAnd) => format!("ncr_i32_and({left_value}, {right_value})"),
                (Type::Int, B::BitOr) => format!("ncr_i32_or({left_value}, {right_value})"),
                (Type::Int, B::BitXor) => format!("ncr_i32_xor({left_value}, {right_value})"),
                (Type::Long, B::BitAnd) => format!("ncr_i64_and({left_value}, {right_value})"),
                (Type::Long, B::BitOr) => format!("ncr_i64_or({left_value}, {right_value})"),
                (Type::Long, B::BitXor) => format!("ncr_i64_xor({left_value}, {right_value})"),
                _ => unreachable!("checked bitwise operation"),
            },
            B::ShiftLeft | B::ShiftRight => match (expr.ty, op) {
                (Type::Int, B::ShiftLeft) => format!("ncr_i32_shl({left_value}, {right_value}, {line}, {column})"),
                (Type::Int, B::ShiftRight) => format!("ncr_i32_shr({left_value}, {right_value}, {line}, {column})"),
                (Type::Long, B::ShiftLeft) => format!("ncr_i64_shl({left_value}, {right_value}, {line}, {column})"),
                (Type::Long, B::ShiftRight) => format!("ncr_i64_shr({left_value}, {right_value}, {line}, {column})"),
                _ => unreachable!("checked shift operation"),
            },
            B::And | B::Or => unreachable!("short-circuit handled before formatting"),
        };
        self.bind(expr.ty, &operation)
    }
}
